// Enhanced language manager that works with the comprehensive system
class EnhancedLanguageManager {
    constructor() {
        this.translations = enhancedTranslations;
        this.init();
    }

    init() {
        // Wait for the main language manager to be ready
        setTimeout(() => {
            if (window.languageManager) {
                // Add our enhanced translations
                Object.keys(this.translations).forEach(lang => {
                    window.languageManager.addTranslations(lang, this.translations[lang]);
                });
                
                // Re-translate the page with enhanced content
                this.addTranslationAttributes();
                window.languageManager.translatePage();
            }
        }, 200);
    }

    addTranslationAttributes() {
        // Add data-translate attributes to common elements that might not have them
        const elementsToTranslate = [
            { selector: 'h1', prefix: 'heading-' },
            { selector: 'h2', prefix: 'subheading-' },
            { selector: 'h3', prefix: 'section-' },
            { selector: '.feature-card h4', prefix: 'feature-' },
            { selector: '.tech-category h3', prefix: 'tech-category-' },
            { selector: '.industry-card h3', prefix: 'industry-' },
            { selector: '.benefit-item h4', prefix: 'benefit-' },
            { selector: '.step-title', prefix: 'step-' },
            { selector: '.cta-button', prefix: 'cta-' }
        ];

        elementsToTranslate.forEach(({ selector, prefix }) => {
            document.querySelectorAll(selector).forEach(element => {
                if (!element.hasAttribute('data-translate')) {
                    const text = element.textContent.trim().toLowerCase()
                        .replace(/[^a-z0-9\s]/g, '')
                        .replace(/\s+/g, '-');
                    if (text) {
                        element.setAttribute('data-translate', prefix + text);
                    }
                }
            });
        });
    }

    // Method to translate specific content types
    translateContent(contentType, element) {
        const currentLang = window.languageManager ? window.languageManager.currentLanguage : 'en';
        const translations = this.translations[currentLang] || this.translations['en'];
        
        if (translations[contentType]) {
            element.textContent = translations[contentType];
        }
    }
}

// Initialize enhanced translations
document.addEventListener('DOMContentLoaded', () => {
    window.enhancedLanguageManager = new EnhancedLanguageManager();
});

